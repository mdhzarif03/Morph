// Writes docs/THIRD_PARTY_LICENSES.md from the installed production dependency tree (name, version, license).
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
const seen = new Map();

async function readPkg(dir) {
  try { return JSON.parse(await fs.readFile(path.join(dir, 'package.json'), 'utf8')); } catch { return null; }
}

async function walk(name, from) {
  let dir = from;
  let found;
  while (true) {
    const candidate = path.join(dir, 'node_modules', name);
    found = await readPkg(candidate);
    if (found) { dir = candidate; break; }
    const parent = path.dirname(dir);
    if (parent === dir) return;
    dir = parent;
  }
  const key = `${found.name}@${found.version}`;
  if (seen.has(key)) return;
  const license = typeof found.license === 'string' ? found.license : found.license?.type ?? found.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN';
  seen.set(key, { name: found.name, version: found.version, license, homepage: found.homepage ?? '' });
  const deps = { ...found.dependencies, ...found.optionalDependencies };
  for (const dep of Object.keys(deps)) await walk(dep, dir);
}

for (const dep of [...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.optionalDependencies ?? {})]) await walk(dep, root);

const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = [
  '# Third-party licenses (npm production dependencies)',
  '',
  'Generated by `npm run licenses` from the installed dependency tree. Re-run after changing dependencies.',
  'External programs (FFmpeg, Poppler, LibreOffice) are covered in `DEPENDENCIES.md`.',
  '',
  '| Package | Version | License |',
  '| --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
].join('\n');
await fs.mkdir(path.join(root, 'docs'), { recursive: true });
await fs.writeFile(path.join(root, 'docs', 'THIRD_PARTY_LICENSES.md'), out);
console.log(`Wrote docs/THIRD_PARTY_LICENSES.md (${rows.length} packages)`);
const unknown = rows.filter((r) => r.license === 'UNKNOWN');
if (unknown.length) console.warn('License not declared for:', unknown.map((r) => r.name).join(', '));
